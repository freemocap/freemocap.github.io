// Prints nginx `location =` blocks (real 301s) for every internal entry in
// data/redirects.js, so legacy URLs redirect at the server instead of relying
// on the client-side redirect pages alone.
//
//   node scripts/gen-nginx-redirects.js > nginx-legacy-redirects.conf
//
// Paste the output into Plesk (Websites & Domains -> docs.freemocap.org ->
// Apache & nginx Settings -> Additional nginx directives). Regenerate whenever
// data/redirects.js changes.
const redirects = require('../data/redirects');

const slash = (p) => (p.endsWith('/') || /\.\w+$/.test(p) ? p : `${p}/`);
const seen = new Set();
const out = ['# Generated by scripts/gen-nginx-redirects.js. Do not edit by hand.'];

for (const { from, to } of redirects) {
  const target = /^https?:/.test(to) ? to : slash(to);
  for (const f of [].concat(from)) {
    // nginx treats /x and /x/ as different exact locations, so emit both.
    const paths = f.endsWith('/') ? [f.slice(0, -1) || '/', f] : f.endsWith('.html') ? [f] : [f, `${f}/`];
    for (const p of paths) {
      if (p === '/' || p === target || seen.has(p)) continue;
      seen.add(p);
      out.push(`location = ${p} { return 301 ${target}; }`);
    }
  }
}

console.log(out.join('\n'));
